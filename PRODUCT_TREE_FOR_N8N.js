// ====== УТИЛИТЫ ДЛЯ РАБОТЫ С ДЕРЕВОМ ======

// Получить все продукты (первый уровень)
function getProducts() {
  return Object.keys(PRODUCT_TREE);
}

// Получить типы для продукта
function getTypes(product) {
  if (!PRODUCT_TREE[product]) return [];
  return Object.keys(PRODUCT_TREE[product]);
}

// Получить subtype1 для продукта и типа
function getSubtype1(product, type) {
  if (!PRODUCT_TREE[product] || !PRODUCT_TREE[product][type]) return [];
  return Object.keys(PRODUCT_TREE[product][type]);
}

// Получить subtype2 (фракции) для продукта, типа и subtype1
function getSubtype2(product, type, subtype1) {
  if (!PRODUCT_TREE[product] || !PRODUCT_TREE[product][type] || !PRODUCT_TREE[product][type][subtype1]) return [];
  return PRODUCT_TREE[product][type][subtype1];
}

// Построить полное название товара
function buildProductName(product, type = '', subtype1 = '', subtype2 = '') {
  const parts = [product];
  if (type) parts.push(type);
  if (subtype1) parts.push(subtype1);
  if (subtype2) parts.push(subtype2);
  return parts.join(' ');
}

